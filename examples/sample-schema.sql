-- Sample multitenant schema used by the tests and as a playground.
-- Load it with: psql "$DATABASE_URL" -f examples/sample-schema.sql

DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;

CREATE TYPE company_status AS ENUM ('active', 'inactive', 'archived');
CREATE DOMAIN email_address AS varchar(320) CHECK (VALUE LIKE '%@%');

-- Global table: no tenant_id, so it is not tenant-scoped.
CREATE TABLE tenants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE tenants IS 'Customers of the platform';

CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  email email_address NOT NULL,
  password_hash text NOT NULL,
  CONSTRAINT users_tenant_email_unique UNIQUE (tenant_id, email)
);

CREATE TABLE company (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  name varchar(255) NOT NULL,
  status company_status NOT NULL DEFAULT 'active',
  tags text[] NOT NULL DEFAULT '{}',
  founded date,
  revenue numeric(12, 2),
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON COLUMN company.name IS 'Legal name';

CREATE TABLE employee (
  id bigserial PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  company_id integer NOT NULL REFERENCES company (id) ON DELETE CASCADE,
  manager_id bigint REFERENCES employee (id) ON DELETE SET NULL,
  first_name text NOT NULL,
  last_name text NOT NULL,
  full_name text GENERATED ALWAYS AS (first_name || ' ' || last_name) STORED,
  salary numeric(10, 2)
);

CREATE TABLE project (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  company_id integer NOT NULL REFERENCES company (id),
  title text NOT NULL
);

-- Junction table with a composite primary key.
CREATE TABLE project_members (
  project_id integer NOT NULL REFERENCES project (id) ON DELETE CASCADE,
  employee_id bigint NOT NULL REFERENCES employee (id) ON DELETE CASCADE,
  tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'member',
  PRIMARY KEY (project_id, employee_id)
);

-- No primary key on purpose.
CREATE TABLE audit_log (
  tenant_id uuid NOT NULL,
  message text NOT NULL,
  logged_at timestamptz NOT NULL DEFAULT now()
);

-- Housekeeping table that the default config excludes.
CREATE TABLE knex_migrations (
  id serial PRIMARY KEY,
  name varchar(255)
);
